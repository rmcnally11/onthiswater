export const AREA_BY_ID = Object.fromEntries(AREAS.map((a) => [a.id, a]));
export const AREA_IDS = AREAS.map((a) => a.id);

export function areasInTheater(theater: Area["theater"]) {
  return AREAS.filter((a) => a.theater === theater);
}

export function waterChipLabel(area: Area) {
  if (area.id === "lower-laguna") return "Lower Laguna";
  if (area.id === "grand-bahama") return "Grand Bahama";
  if (area.id === "isla-mujeres") return "Isla Mujeres";
  if (area.id === "hilton-head") return "Hilton Head";
  if (area.id === "sao-miguel") return "São Miguel";
  return area.shortName;
}

export function getArea(id?: string | null) {
  return AREA_BY_ID[id ?? ""] ?? AREA_BY_ID.galveston;
}

export function neighborArea(area: Area): Area {
  const same = AREAS.filter((a) => a.theater === area.theater);
  const i = same.findIndex((a) => a.id === area.id);
  const next = same[i + 1] ?? same[i - 1];
  if (next && next.id !== area.id) return next;
  return AREAS.find((a) => a.id !== area.id) ?? area;
}

export function defaultOffshoreLeads(area: Area): SpeciesId[] {
  return SPECIES.filter(
    (s) =>
      s.theaters.includes(area.theater) &&
      (s.role === "bluewater" || (s.role === "pacific" && area.theater === "mexico")),
  ).map((s) => s.id);
}

export function leadsFor(area: Area, activity: ActivityId | "all"): SpeciesId[] {
  if (activity === "offshore") {
    return [...new Set([...(area.offshoreLead ?? []), ...defaultOffshoreLeads(area)])];
  }
  return area.leadSpecies;
}

export function usesModeledOcean(area: Area) {
  return (
    area.theater === "bahamas" ||
    area.theater === "mexico" ||
    area.theater === "seychelles" ||
    area.theater === "azores"
  );
}
