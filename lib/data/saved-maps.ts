function miles(aLat: number, aLon: number, bLat: number, bLon: number) {
  const dlat = aLat - bLat;
  const dlon = (aLon - bLon) * Math.cos((aLat * Math.PI) / 180);
  return Math.hypot(dlat, dlon) * 69;
}

function habitatFor(pin: SavedPin): Habitat {
  const n = `${pin.name} ${pin.note} ${pin.folder}`.toLowerCase();
  if (n.includes("troll") || n.includes("offshore") || n.includes("color change") || n.includes("weedline")) {
    return "blue-water";
  }
  if (n.includes("wreck") || n.includes("hump")) return "wreck-edge";
  if (n.includes("jetty") || n.includes("pass") || n.includes("inlet") || n.includes("bridge")) return "pass-jetty";
  if (n.includes("beach") || n.includes("surf") || n.includes("2wd") || n.includes("4wd")) return "sand-dropoff";
  if (n.includes("rock") || n.includes("baffin") || n.includes("serpulid")) return "serpulid-reef";
  if (n.includes("mangrove") || n.includes("marsh") || n.includes("backcountry")) return "mangrove-edge";
  if (n.includes("channel") || n.includes("drift") || n.includes("cut")) return "channel-gut";
  return "grass-flat";
}

function activitiesFor(pin: SavedPin): ActivityId[] {
  const n = `${pin.name} ${pin.folder}`.toLowerCase();
  if (n.includes("troll") || n.includes("offshore") || n.includes("color change") || n.includes("hump") || n.includes("weedline")) {
    return ["offshore", "spin"];
  }
  if (n.includes("jetty") || n.includes("wreck") || n.includes("bridge")) {
    return ["structure", "skiff", "spin", "fly"];
  }
  if (n.includes("beach") || n.includes("surf") || n.includes("camp")) return ["structure", "spin", "wade"];
  return ["skiff", "kayak", "wade", "fly", "spin"];
}

function speciesFor(pin: SavedPin, area: Area): SpeciesId[] {
  const n = `${pin.name} ${pin.note} ${pin.folder}`.toLowerCase();
  if (n.includes("troll") || n.includes("offshore") || n.includes("color change")) {
    return ["mahi", "tuna", "sailfish"];
  }
  if (area.id === "florida-bay") return ["redfish", "snook", "tarpon"];
  if (area.theater === "mexico") {
    if (n.includes("troll") || n.includes("offshore") || n.includes("bank")) return ["mahi", "tuna", "sailfish", "roosterfish"];
    return [...area.leadSpecies];
  }
  if (area.theater === "florida" || area.theater === "bahamas") {
    if (n.includes("tarpon") || n.includes("bridge")) return ["tarpon", "permit"];
    if (n.includes("wreck") || n.includes("hump")) return ["permit", "tarpon"];
    return [...area.leadSpecies];
  }
  return area.leadSpecies.length ? [...area.leadSpecies] : ["redfish", "speckled-trout"];
}

/** How far a desk’s chart and saved pins may reach. Tight on purpose so Flamingo ≠ Islamorada. */
export function deskAtlasMiles(area: Area) {
  if (area.id === "florida-bay" || area.id === "calcasieu" || area.id === "key-largo") return 16;
  if (area.id === "boca-grande" || area.id === "jupiter" || area.id === "venice" || area.id === "grand-isle") return 18;
  if (area.theater === "florida") return 22;
  if (area.theater === "bahamas" || area.theater === "mexico" || area.theater === "seychelles" || area.theater === "azores") return 40;
  if (area.theater === "puerto-rico" || area.theater === "north-carolina" || area.theater === "south-carolina") return 28;
  return 42;
}

export function withinDesk(area: Area, lat: number, lon: number, maxMiles?: number) {
  return miles(area.lat, area.lon, lat, lon) <= (maxMiles ?? deskAtlasMiles(area));
}

/** Fishing / access marks from your My Maps, near this micro-area. Closed polygons stay off the brief. */
export function savedSpotsNear(
  area: Area,
  maxMiles?: number,
  opts?: { includeOffshore?: boolean },
): Spot[] {
  const radius = maxMiles ?? deskAtlasMiles(area);
  return SAVED_PINS.filter((p) => p.kind === "fish" || p.kind === "access")
    .filter((p) => {
      const n = `${p.name} ${p.folder}`.toLowerCase();
      const offshorePin =
        n.includes("troll") || n.includes("color change") || n.includes("offshore run") || n.includes("hump");
      if (offshorePin) return Boolean(opts?.includeOffshore);
      return true;
    })
    .filter((p) => miles(area.lat, area.lon, p.lat, p.lon) <= radius)
    .map((p) => ({
      id: p.id,
      areaId: area.id,
      name: p.name,
      lat: p.lat,
      lon: p.lon,
      habitat: habitatFor(p),
      activities: activitiesFor(p),
      species: speciesFor(p, area),
      source: "saved-map" as const,
      note: [p.note, p.folder, p.mapTitle].filter(Boolean).join(" · "),
      depth: p.kind === "access" ? ("mid" as const) : nDepth(p),
    }));
}

function nDepth(p: SavedPin): "skinny" | "mid" | "deep" {
  const n = `${p.name} ${p.folder}`.toLowerCase();
  if (n.includes("wreck") || n.includes("hump") || n.includes("offshore") || n.includes("troll")) return "deep";
  if (n.includes("flats") || n.includes("bank") || n.includes("laguna")) return "skinny";
  return "mid";
}

export function savedMarksNear(
  area: Area,
  maxMiles?: number,
  opts?: { includeOffshore?: boolean },
): OfficialMark[] {
  const radius = maxMiles ?? deskAtlasMiles(area);
  return SAVED_PINS.filter((p) => miles(area.lat, area.lon, p.lat, p.lon) <= radius)
    .filter((p) => p.kind !== "route")
    .filter((p) => {
      const n = `${p.name} ${p.folder}`.toLowerCase();
      const offshorePin =
        n.includes("troll") || n.includes("color change") || n.includes("offshore run") || n.includes("hump");
      if (offshorePin) return Boolean(opts?.includeOffshore);
      return true;
    })
    .map((p) => {
      const n = `${p.name} ${p.folder}`.toLowerCase();
      const troll = n.includes("troll") || n.includes("color change");
      const legal = !troll && (p.kind === "closed" || p.kind === "caution");
      return {
        id: p.id,
        name: p.name,
        lat: p.lat,
        lon: p.lon,
        kind: legal ? ("fknms-zone" as const) : ("saved-map" as const),
        source: p.mapTitle,
        sourceUrl: p.mapUrl,
        detail: [p.folder, p.note].filter(Boolean).join(" · "),
        legal,
      };
    });
}
